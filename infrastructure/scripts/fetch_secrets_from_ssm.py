#!/usr/bin/env python3
"""
RIGHT FIT — AWS SSM Parameter Store Secret Injector
Fetches parameters under path /rightfit/production/ and writes to .env.production
Uses IAM Instance Profile credentials (no hardcoded keys).
"""

import os
import sys
import boto3
from botocore.exceptions import ClientError

def fetch_ssm_parameters(prefix="/rightfit/production/", region="us-east-1"):
    print(f"[SSM Injector] Fetching production secrets from AWS SSM (prefix: {prefix}, region: {region})...")
    
    try:
        ssm = boto3.client("ssm", region_name=region)
    except Exception as e:
        print(f"[SSM Injector] ERROR: Could not initialize SSM client: {e}", file=sys.stderr)
        return {}

    parameters = {}
    next_token = None

    while True:
        try:
            kwargs = {
                "Path": prefix,
                "Recursive": True,
                "WithDecryption": True,
            }
            if next_token:
                kwargs["NextToken"] = next_token

            response = ssm.get_parameters_by_path(**kwargs)
            for param in response.get("Parameters", []):
                name = param["Name"].replace(prefix, "")
                value = param["Value"]
                parameters[name] = value

            next_token = response.get("NextToken")
            if not next_token:
                break
        except ClientError as e:
            print(f"[SSM Injector] AWS API ClientError: {e}", file=sys.stderr)
            break
        except Exception as e:
            print(f"[SSM Injector] Unexpected error: {e}", file=sys.stderr)
            break

    print(f"[SSM Injector] Successfully fetched {len(parameters)} parameters.")
    return parameters

def write_env_file(parameters, output_file=".env.production"):
    if not parameters:
        print("[SSM Injector] No parameters retrieved; skipping file write.")
        return False

    with open(output_file, "w") as f:
        f.write("# Auto-generated by fetch_secrets_from_ssm.py from AWS SSM Parameter Store\n")
        f.write(f"# Timestamp: {os.popen('date').read().strip()}\n\n")
        for k, v in sorted(parameters.items()):
            f.write(f"{k}={v}\n")

    # Set restrictive permissions (chmod 600 on POSIX)
    try:
        os.chmod(output_file, 0o600)
    except Exception:
        pass

    print(f"[SSM Injector] Wrote parameters to {output_file} with restricted file permissions (0600).")
    return True

if __name__ == "__main__":
    prefix = os.environ.get("SSM_PREFIX", "/rightfit/production/")
    region = os.environ.get("AWS_REGION", "us-east-1")
    params = fetch_ssm_parameters(prefix=prefix, region=region)
    write_env_file(params)

